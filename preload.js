const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('lol', {
  lang: ipcRenderer.sendSync('i18n:lang'), // Sprache der Oberfläche (de/en), fürs Übersetzen beim Laden

  onGame: (cb) => ipcRenderer.on('game', (_e, d) => cb(d)),
  onEditMode: (cb) => ipcRenderer.on('edit-mode', (_e, on) => cb(on)),
  onScoreboard: (cb) => ipcRenderer.on('scoreboard-state', (_e, s) => cb(s)),
  onTabHeld: (cb) => ipcRenderer.on('tab-held', (_e, on) => cb(on)),
  onPanelPos: (cb) => ipcRenderer.on('panel-pos', (_e, p) => cb(p)),
  panelMoved: (pos) => ipcRenderer.invoke('panel-moved', pos),
  uiHover: (over) => ipcRenderer.send('ui-hover', over),
  hitRects: (r) => ipcRenderer.send('hit-rects', r),
  onPanelHover: (cb) => ipcRenderer.on('panel-hover', (_e, on) => cb(on)),
  onOverlaySettings: (cb) => ipcRenderer.on('overlay-settings', (_e, s) => cb(s)),
  setOverlay: (patch) => ipcRenderer.invoke('overlay:set', patch),
  onSettingsOpen: (cb) => ipcRenderer.on('settings-open', (_e, on) => cb(on)),
  settingsOpen: (on) => ipcRenderer.send('overlay:settingsOpen', on),
  endOfGame: () => ipcRenderer.invoke('stats:eog'),
  history: () => ipcRenderer.invoke('stats:history'),
  summoner: () => ipcRenderer.invoke('stats:summoner'),
  champion: (id) => ipcRenderer.invoke('ddragon:champion', id),
  ddVersion: () => ipcRenderer.invoke('ddragon:version'),
  calibCheck: () => ipcRenderer.invoke('calib:check'),
  liveData: () => ipcRenderer.invoke('live:data'),
  buildData: () => ipcRenderer.invoke('build:data'),
  setBuild: (champId, ids) => ipcRenderer.invoke('build:set', champId, ids),
  saveRunes: (champId) => ipcRenderer.invoke('runes:saveCurrent', champId),
  applyRunes: (champId) => ipcRenderer.invoke('runes:apply', champId),
  setRunesAuto: (on) => ipcRenderer.invoke('runes:auto', on),
  setSpellsAuto: (on) => ipcRenderer.invoke('spells:auto', on),
  statsUsed: () => ipcRenderer.send('stats:used'),
  statsWindow: (action) => ipcRenderer.send('stats:window', action),
  matchup: (champId, vsId, position) => ipcRenderer.invoke('matchup:get', champId, vsId, position),
  matchupState: () => ipcRenderer.invoke('matchup:state'),
  jungleRoutes: (champId) => ipcRenderer.invoke('jungle:routes', champId),
  jungleChoose: (champId, start) => ipcRenderer.invoke('jungle:choose', champId, start),
  onMatchupEnemies: (cb) => ipcRenderer.on('matchup:enemies', (_e, s) => cb(s)),
  popupMenu: (pos) => ipcRenderer.send('menu:popup', pos),
  applySpells: () => ipcRenderer.invoke('spells:apply'),
  suggestion: (champId, load) => ipcRenderer.invoke('suggestion:get', champId, load),
  runeOptions: (champId) => ipcRenderer.invoke('runes:options', champId),
  useRuneOption: (champId, i, save) => ipcRenderer.invoke('runes:useOption', champId, i, save),
  takeSuggestion: (champId, what) => ipcRenderer.invoke('suggestion:take', champId, what),
  setSuggestions: (on) => ipcRenderer.invoke('suggestion:enabled', on),
  openSource: (url) => ipcRenderer.invoke('suggestion:open', url),
  onSuggestion: (cb) => ipcRenderer.on('suggestion', (_e, champId) => cb(champId)),
  onBuildChampion: (cb) => ipcRenderer.on('build:champion', (_e, id) => cb(id)),
  onShowTab: (cb) => ipcRenderer.on('show-tab', (_e, tab) => cb(tab)),
  importItemSet: (champId) => ipcRenderer.invoke('build:itemSet', champId),
  setItemSetAuto: (on) => ipcRenderer.invoke('build:itemSetAuto', on),
  onBuildStatus: (cb) => ipcRenderer.on('build:status', (_e, msg) => cb(msg)),
  setOpenInChampSelect: (on) => ipcRenderer.invoke('build:openInChampSelect', on),
  setAutoAccept: (on) => ipcRenderer.invoke('queue:autoAccept', on),
  onAutoAccept: (cb) => ipcRenderer.on('autoAccept', (_e, on) => cb(on)),
  onRunesStatus: (cb) => ipcRenderer.on('runes:status', (_e, msg) => cb(msg)),
  onSpellsStatus: (cb) => ipcRenderer.on('spells:status', (_e, msg) => cb(msg)),
  bench: () => ipcRenderer.invoke('bench:get'),
  onBench: (cb) => ipcRenderer.on('bench', (_e, info) => cb(info)),
  ownItems: (champId) => ipcRenderer.invoke('history:items', champId),
  takeOwnItems: (champId) => ipcRenderer.invoke('history:take', champId),
  onOwnItems: (cb) => ipcRenderer.on('history:items', () => cb()),
});
